export function translateUi(text, lang) {
  if (lang !== 'en') return text;
  const raw = String(text);
  const trimmed = raw.trim();
  if (!trimmed) return raw;
  if (UI_EN[trimmed]) return raw.replace(trimmed, UI_EN[trimmed]);
  for (const p of UI_PATTERNS) {
    const m = trimmed.match(p.tr);
    if (m) return raw.replace(trimmed, p.en(m));
  }
  return raw;
}
